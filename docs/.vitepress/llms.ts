// llms.txt for coding agents (https://llmstxt.org), written at build time
// from the docs sources so it can't drift from the site:
//
//   /llms.txt          index: a summary, then every sidebar page as a link
//                      to its markdown copy, grouped and ordered like the
//                      sidebar, with its tagline as the description
//   /llms-full.txt     every sidebar page in order, one file (the API map
//                      isn't in the sidebar — 80 KB of table; linked instead)
//   /docs/<page>.md    each page's markdown next to its HTML
//
// Copies are the source minus frontmatter and the generated-file comment,
// the tagline turned into a quote, and links rewritten: ./page → ./page.md
// in the copies, absolute https://tinyjs.app/… in llms-full.txt. ::: tabs and
// the other containers stay as written; they read fine as text.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'
import type { DefaultTheme, SiteConfig } from 'vitepress'

const SITE = 'https://tinyjs.app'
const SKILL = 'https://github.com/tarwin/tinyjsapp/tree/main/skill'

const SUMMARY = `> tinyjs makes ~6 MB desktop apps for macOS, Windows and Linux in JavaScript: a txiki.js backend (files, sockets, processes, FFI — not Node) and a native webview window (WKWebView, WebView2, WebKitGTK). The page reaches the system only through \`window.tiny\`; the backend has the same calls on its \`app\` handle.

Key facts:

- A project is \`tinyjs.json\` + \`src/frontend/\` (the page) + \`src/backend/main.js\` (\`export const api = { … }\`, called from the page with \`tiny.api.call(name, args)\`).
- The backend runs txiki.js: use \`tjs.*\` for files and processes; Node built-ins (\`fs\`, \`path\`, \`child_process\`) don't exist.
- \`tinyjs new <dir>\` scaffolds, \`tinyjs dev\` runs with reload, \`tinyjs build\` makes the app, \`tinyjs doctor\` diagnoses.
- Where an OS can't do something, the call rejects or answers \`'unsupported'\`; the docs say which per call.
- Every project ships \`types/tiny.d.ts\` and \`types/tjs.d.ts\` — the authoritative signatures — and an agent skill in \`.claude/skills/tinyjs/\` and \`.agents/skills/tinyjs/\` (source: ${SKILL}).`

type Page = { text: string; slug: string; src: string }

const slugOf = (link: string) => link.replace(/^\/docs\/?/, '') || 'index'

function readPage(srcDir: string, slug: string) {
  return readFileSync(join(srcDir, 'docs', slug + '.md'), 'utf8')
}

// Some taglines carry <code> and <a>; markdown reads better as text.
const unhtml = (s: string) => s
  .replace(/<code>(.*?)<\/code>/g, '`$1`')
  .replace(/<a href="([^"]*)"[^>]*>(.*?)<\/a>/g, '[$2]($1)')

// Frontmatter, the generated-file marker and the tagline paragraph out; the
// tagline comes back as a quote under the title.
function clean(src: string) {
  return src
    .replace(/^---\n[\s\S]*?\n---\n+/, '')
    .replace(/^<!-- Generated by [^\n]*-->\n+/m, '')
    .replace(/^<p class="tagline">(.*)<\/p>$/m, (_, t) => '> ' + unhtml(t))
    .trim() + '\n'
}

// The page's tagline, else its first prose paragraph, for the index.
function describe(src: string) {
  const tagline = src.match(/<p class="tagline">(.*)<\/p>/)
  if (tagline) return unhtml(tagline[1]).replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
  const para = clean(src).split(/\n{2,}/).find((p) => /^[A-Za-z`*[]/.test(p)) ?? ''
  const flat = para.replace(/\[([^\]]*)\]\([^)]*\)/g, '$1').replace(/\s+/g, ' ').trim()
  const first = flat.match(/^.*?[.!?](?=\s|$)/)?.[0] ?? flat
  return first.length > 160 ? first.slice(0, 157) + '…' : first
}

// ./page and ./page#x → ./page.md(#x) (a copy's sibling copies), or the full
// site URL; root links (/images, /changelog) → absolute.
function relinkCopy(md: string) {
  return md
    .replace(/\]\(\.\/([\w-]+)(#[^)]*)?\)/g, (_, p, h = '') => `](./${p}.md${h})`)
    .replace(/\]\(\/(?!\/)/g, `](${SITE}/`)
}
function relinkFull(md: string) {
  return md
    .replace(/\]\(\.\/([\w-]+)(#[^)]*)?\)/g, (_, p, h = '') => `](${SITE}/docs/${p}${h})`)
    .replace(/\]\(\/(?!\/)/g, `](${SITE}/`)
}

export function writeLlms(site: SiteConfig, sidebar: DefaultTheme.SidebarItem[]) {
  const groups = sidebar.map((g) => ({
    text: g.text!,
    pages: (g.items ?? []).map((i): Page => {
      const slug = slugOf(i.link!)
      return { text: i.text!, slug, src: readPage(site.srcDir, slug) }
    }),
  }))

  const index = [
    '# tinyjs', '', SUMMARY, '',
    ...groups.flatMap((g) => [
      `## ${g.text}`, '',
      ...g.pages.map((p) => `- [${p.text}](${SITE}/docs/${p.slug}.md): ${describe(p.src)}`),
      '',
    ]),
    '## Optional', '',
    `- [All docs in one file](${SITE}/llms-full.txt): every page above, in this order`,
    `- [API map](${SITE}/docs/api-map.md): every \`app\` call next to its \`tiny\` twin, generated from tiny.d.ts`,
    `- [tinyjs.json schema](${SITE}/schema/tinyjs.schema.json): JSON Schema for the project file`,
    `- [Changelog](https://github.com/tarwin/tinyjsapp/blob/main/CHANGELOG.md)`,
    `- [Agent skill](${SKILL}): the reference \`tinyjs new\` puts in every project`,
    `- [Example apps](https://github.com/tarwin/tinyjsapp-examples)`,
    '',
  ].join('\n')
  writeFileSync(join(site.outDir, 'llms.txt'), index)

  const full = [
    '# tinyjs', '', SUMMARY, '',
    ...groups.flatMap((g) => g.pages.map((p) => `<!-- ${SITE}/docs/${p.slug} -->\n\n${relinkFull(clean(p.src))}`)),
  ].join('\n')
  writeFileSync(join(site.outDir, 'llms-full.txt'), full)

  // the API map isn't in the sidebar but gets a copy too
  mkdirSync(join(site.outDir, 'docs'), { recursive: true })
  const slugs = new Set([...groups.flatMap((g) => g.pages.map((p) => p.slug)), 'api-map'])
  for (const slug of slugs)
    writeFileSync(join(site.outDir, 'docs', slug + '.md'), relinkCopy(clean(readPage(site.srcDir, slug))))
}
